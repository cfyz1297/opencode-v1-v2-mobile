// "Text is cut in half in the middle of a message" on Android 15+.
//
// React Native measures <Text> with a StaticLayout that breaks lines on glyph
// advances, but on Android 15+ (targetSdk 35+) the TextView that actually
// paints it breaks on glyph bounds (TextView#USE_BOUNDS_FOR_WIDTH). With a font
// whose ink overhangs its advance the drawn layout wraps one line later than
// the measured one, and that line lands outside the measured height: the last
// line is clipped. Upstream fixed ReactTextView in 0.89
// (https://github.com/facebook/react-native/pull/58280); this app is on 0.88.1
// and builds against the prebuilt react-android AAR, so the same flag is set
// through the theme's android:textViewStyle — AppCompatTextView (ReactTextView's
// parent) resolves it for every text view RN creates.
//
// android/ is regenerated by prebuild, so the switch lives in the config plugin
// and is pinned here: a dropped step must fail a test, not the phone.
import { test } from "node:test"
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import path from "node:path"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..")
const read = (file: string) => readFileSync(path.join(root, file), "utf8")
const requireCjs = createRequire(import.meta.url)

const STYLE = "OpencodeAdvanceTextView"

interface StyleItem {
  $: { name: string }
  _: string
}
interface StyleGroup {
  $: { name: string; parent?: string }
  item: StyleItem[]
}
interface StylesXml {
  resources: { style: StyleGroup[] }
}

function apply(xml: StylesXml): StylesXml {
  const { applyAdvanceBasedTextStyle } = requireCjs("../../plugins/with-native-customizations.js")
  return applyAdvanceBasedTextStyle(xml)
}

function appThemeXml(): StylesXml {
  return {
    resources: {
      style: [
        {
          $: { name: "AppTheme", parent: "Theme.AppCompat.DayNight.NoActionBar" },
          item: [{ $: { name: "android:editTextBackground" }, _: "@drawable/rn_edit_text_material" }],
        },
      ],
    },
  }
}

function textViewItem(xml: StylesXml): StyleItem | undefined {
  const appTheme = xml.resources.style.find((group) => group.$.name === "AppTheme")!
  return appTheme.item.find((item) => item.$.name === "android:textViewStyle")
}

test("every text view is switched back to advance-based line breaking", () => {
  const xml = apply(appThemeXml())
  const style = xml.resources.style.find((group) => group.$.name === STYLE)
  assert.ok(style, "the textViewStyle override style is missing")
  // Same parent AppCompat's own textViewStyle uses, so nothing else changes.
  assert.equal(style.$.parent, "android:Widget.TextView")
  assert.deepEqual(style.item, [{ $: { name: "android:useBoundsForWidth" }, _: "false" }])
  assert.equal(textViewItem(xml)?._, `@style/${STYLE}`)
})

test("prebuild re-runs cannot duplicate or revert the override", () => {
  const once = apply(appThemeXml())
  const twice = apply(apply(appThemeXml()))
  assert.deepEqual(twice, once)
  // The rest of AppTheme survives the edit.
  const appTheme = twice.resources.style.find((group) => group.$.name === "AppTheme")!
  assert.equal(appTheme.item.filter((item) => item.$.name === "android:textViewStyle").length, 1)
  assert.ok(appTheme.item.some((item) => item.$.name === "android:editTextBackground"))
})

test("a styles.xml without AppTheme fails prebuild instead of silently keeping the bug", () => {
  assert.throws(() => apply({ resources: { style: [] } }), /AppTheme/)
})

test("the plugin applies the style step and ships it in the mod chain", () => {
  const plugin = read("plugins/with-native-customizations.js")
  assert.match(plugin, /withAndroidStyles/)
  assert.match(plugin, /withAdvanceBasedText\(/)
})
